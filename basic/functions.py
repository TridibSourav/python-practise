# Function without parameters

def greet():
    print("Welcome to Python")

greet()

# Function with parameters

def add_numbers(a, b):
    result = a + b
    print("Sum:", result)

add_numbers(5, 3)

# Function with return value

def multiply(x, y):
    return x * y

answer = multiply(4, 6)

print("Multiplication:", answer)
